function updateTotal(){
    let total = 0;
    $("#orderTable tbody tr").each(function(){
        let qty = parseFloat($(this).find(".quantityInput").val()) || 0;
        let price = parseFloat($(this).find(".priceInput").val()) || 0;
        let subTotal = qty * price;
        
        $(this).find(".totalInput").text(subTotal.toFixed(2));
        total += subTotal;
    });
    $("#totalAmount").text(total.toFixed(2));
}

