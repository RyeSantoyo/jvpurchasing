let dataTableInstance;
let autoGeneratedPoNumber = "";

$(document).ready(function () {
    dataTableInstance = $('#potable').DataTable({
        "order": [[4, "desc"]], 
        "processing": true, 
        "serverSide": true,
        "responsive": true, 
        "ajax": {
            "url": "/api/po/purchaseorder",
            "headers": {
                "Authorization": "Bearer " + localStorage.getItem("jwtToken")
            },
            "dataSrc": "data", 
            "error": function (xhr, error, thrown) {
                console.error("API Error: ", xhr.status, thrown);
                alert("Failed to load purchase orders. Ensure API is active.");
            }
        },
        "columns": [
            { "data": "poid", "className": "text-center fw-bold" },
            { "data": "poNumber" },
            { "data": "roNumber", "className": "text-center" },
            { "data": "companyCode", "className": "text-center" },
            { "data": "deliveryAddress", "className": "text-center" },
            { "data": "agreedTerms", "className": "text-center" },
            { 
                "data": "totalAmount",
                "className": "text-center fw-bold",
                "render": function (data, type, row) {
                    if (type === 'display' && data !== null) {
                        return new Intl.NumberFormat('en-US', { 
                            style: 'currency', 
                            currency: 'PHP' 
                        }).format(data);
                    }
                    return data;
                }
            },
            {
                "data": "poid",
                "orderable": false,
                "className": "text-center",
                "render": function (data, type, row) {
                    const poNumSafe = String(row.poNumber || '').replace(/'/g, "\\'");
                    const roNumSafe = String(row.roNumber ?? '').replace(/'/g, "\\'");
                    const addressSafe = String(row.deliveryAddress || '').replace(/'/g, "\\'");
                    const termsSafe = String(row.agreedTerms || '').replace(/'/g, "\\'");
                    const amountSafe = row.totalAmount || 0;

                    return `
                        <div class="btn-group" role="group">
                            <button class="btn btn-sm btn-info text-white" onclick="viewOrder('${data}', '${poNumSafe}', '${addressSafe}', '${termsSafe}', ${amountSafe}, '${roNumSafe}')">
                                <i class="bi bi-eye"></i> View
                            </button>
                            <button class="btn btn-sm btn-warning" onclick="editOrder('${data}')">
                                <i class="bi bi-pencil-square"></i> Edit
                            </button>
                            <button class="btn btn-sm btn-danger" onclick="confirmDelete('${data}', '${poNumSafe}')">
                                <i class="bi bi-trash"></i> Delete
                            </button>
                        </div>
                    `;
                }
            }
        ],
        "language": {
            "emptyTable": "No purchase orders found matching this criteria.",
            "loadingRecords": "Fetching JV purchasing details..."
        }
    });

    // Event listener for manual PO toggle
    $('#chkManualPo').on('change', function(){
        const isManual = $(this).is(':checked');
        const poInput = $('#poNumber');

        if(isManual){
            poInput.prop('readonly', false).val('').focus();
        } else {
            poInput.prop('readonly', true).val(autoGeneratedPoNumber);
        }
    });

    // Delegated events for dynamic rows
    $(document).on('click', '#btnAddOrder', function () {
        addOrderRow();
    });

    $(document).on('input', '.quantityInput, .priceInput', function(){
        updateTotal();
    });

    $(document).on("click", ".removeOrderRow, .remove-row", function(){
        $(this).closest("tr").remove();
        updateTotal();
    });
});

function refreshTable() {
    if (dataTableInstance) {
        dataTableInstance.ajax.reload(null, false); 
    }
}

