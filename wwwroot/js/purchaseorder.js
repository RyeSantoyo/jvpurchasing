function submitPO(){
    let poNumber = $("#poNumber").val().trim();
    let isManual = $("#chkManualPo").is(":checked");

    if(isManual && !poNumber){
        alert("Please enter a manual PO number.");
        $("#poNumber").focus();
        return;
    }

    let roNumber = $("#roNumber").val();
    let companyId = $("#companyId").val();
    let supplierId = $("#supplierId").val();
    let deliveryAddressId = $("#deliveryAddressId").val();
    let orderBy = $("#orderBy").val();
    let requestedBy = $("#requestedBy").val();
    let termsId = $("#termsId").val();
    let orderDate = $("#orderDate").val();
    let orderDetails = [];
    let totalAmount = 0;

    if(!supplierId || !termsId || !orderDate || !companyId || !deliveryAddressId){
        alert("Please fill in all required fields.");
        return;
    }

    $("#orderTable tbody tr").each(function(){
        let product = $(this).find(".product-input").val();
        let unit = $(this).find(".unitInput").val();
        let quantity = parseFloat($(this).find(".quantityInput").val()) || 0;
        let price = parseFloat($(this).find(".priceInput").val()) || 0;

        if(product && unit && quantity > 0 && price > 0){
            let lineTotal = quantity * price;
            totalAmount += lineTotal;

            orderDetails.push({
                companyId: parseInt(companyId),
                companyCode: $("#companyId option:selected").text(),
                poNumber: poNumber,
                description: product,
                unit: unit,
                quantity: quantity,
                price: price,
                total: lineTotal
            });
        }
    });

    if(orderDetails.length === 0){
        alert("Please add at least one valid order detail.");
        return;
    }

    let payload = {
        companyId: parseInt(companyId),
        companyCode: $("#companyId option:selected").text(),
        poNumber: poNumber,
        isManual: isManual,
        poDate: orderDate,
        roNumber: roNumber,                    
        supplierId: parseInt(supplierId),
        supplierName: $("#supplierId option:selected").text(),
        supplierAddress: $("#supplierId option:selected").data("supplierAddress") || "N/A",
        termsId: parseInt(termsId),
        deliveryAddressId: parseInt(deliveryAddressId),
        deliveryAddress: $("#deliveryAddressId option:selected").text(),
        requestedBy: requestedBy,
        orderBy: orderBy,
        remarks: "Testing PO submission",
        poDetails: orderDetails
    };

    $.ajax({
        url: '/api/po/createpo',
        type: 'POST',
        contentType: 'application/json',
        data: JSON.stringify(payload),
        headers: {
            'Authorization': 'Bearer ' + localStorage.getItem("jwtToken")
        },
        success: function(result){
            alert("Purchase Order created successfully!");
            let modalEl = document.getElementById('myModal');
            let modalInstance = bootstrap.Modal.getInstance(modalEl);
            if(modalInstance) modalInstance.hide();
            refreshTable();
        },
        error: function(xhr, status, error){
            console.error("Error creating PO:", xhr.status, error);
            alert("Failed to create Purchase Order. Check API connection.");
        }
    }); 
}

async function printOrder() {
    const poNumber = $("#viewPoNumber").text();
    const token = localStorage.getItem("jwtToken");

    try {
        const response = await fetch(`/api/po/printpo/${poNumber}`, {
            method: "GET",
            headers: {
                'Authorization': 'Bearer ' + token
            }
        });

        if (!response.ok) {
            console.error("Print Error:", response.status);
            return;
        }

        const blob = await response.blob();
        const url = window.URL.createObjectURL(blob);
        window.open(url, "_blank");
    } catch (error) {
        console.error("Print request failed:", error);
    }
}        

