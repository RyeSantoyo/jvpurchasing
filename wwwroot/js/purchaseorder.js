function viewOrder(id, poNum, address, terms, amount, roNum) {
    const modalEl = document.getElementById('viewModal');
    if (!modalEl) return;

    document.body.appendChild(modalEl);

    $("#viewPoId").text(id);
    $("#viewPoNumber").text(poNum);
    $("#viewRoNumber").text(roNum);
    $("#viewDeliveryAddress").text(address);
    $("#viewAgreedTerms").text(terms);

    const rawAmount = parseFloat(amount) || 0;
    const formattedAmount = new Intl.NumberFormat('en-US', { 
        style: 'currency', 
        currency: 'PHP' 
    }).format(rawAmount);
    $("#viewTotalAmount").text(formattedAmount);

    let viewModal = bootstrap.Modal.getInstance(modalEl) || new bootstrap.Modal(modalEl);
    viewModal.show();
}

function editOrder(id) {
    const modalEl = document.getElementById('editModal');
    const token = localStorage.getItem("jwtToken");

    getCompanies();
    getSuppliers();
    getDeliveryAddress();
    getTerms();

    if (!modalEl) return;
    document.body.appendChild(modalEl);

    $.ajax({
        url: `/api/po/purchaseorder/${id}`,
        type: 'GET',
        headers: { 'Authorization': 'Bearer ' + token },
        success: function (po) {
            $("#editPoId").val(po.id || po.poid);
            $("#editPoNumber").val(po.poNumber);
            $("#editRoNumber").val(po.roNumber);
            $("#editCompanyId").val(po.companyId);
            $("#editSupplierId").val(po.supplierId);
            $("#editDeliveryAddressId").val(po.deliveryAddressId);
            $("#editAgreedTermsId").val(po.termsId);
            $("#editTotalAmount").val(po.totalAmount);

            let $tbody =$("#editOrderTable tbody");
            $tbody.empty();

            if (po.poDetails && po.poDetails.length > 0) {
                po.poDetails.forEach(item => {
                    let description = item.description || item.product || '';
                    let row = `
                        <tr>
                            <td><input type="text" class="form-control product-input" value="${description}" /></td>
                            <td><input type="text" class="form-control unitInput" value="${item.unit || ''}" /></td>
                            <td><input type="number" class="form-control quantityInput" value="${item.quantity}" /></td>
                            <td><input type="number" class="form-control priceInput" value="${item.price}" /></td>
                            <td><button type="button" class="btn btn-danger btn-sm remove-row"><i class="bi bi-trash"></i></button></td>
                        </tr>`;
                    $tbody.append(row);
                });
            }

            let editModal = bootstrap.Modal.getInstance(modalEl) || new bootstrap.Modal(modalEl);
            editModal.show();
        },
        error: function (xhr) {
            console.error("Failed to fetch PO details:", xhr);
            alert("Could not load PO details for editing.");
        }
    });
}

function submitEdit(event) {
    event.preventDefault();

    const id = $("#editPoId").val();
    const payload = {
        poid: parseInt(id),
        poNumber: $("#editPoNumber").val(),
        deliveryAddress: $("#editDeliveryAddressId option:selected").text(),
        agreedTerms: $("#editAgreedTermsId option:selected").text(),
        totalAmount: parseFloat($("#editTotalAmount").val())
    };

    $.ajax({
        url: `/api/po/${id}`,
        headers: {
            'Authorization': 'Bearer ' + localStorage.getItem("jwtToken")
        },
        type: 'PUT',
        contentType: 'application/json',
        data: JSON.stringify(payload),
        success: function (result) {
            let editModalEl = document.getElementById('editModal');
            let modalInstance = bootstrap.Modal.getInstance(editModalEl);
            if(modalInstance) modalInstance.hide();

            refreshTable();
            alert("Purchase Order updated successfully!");
        },
        error: function (xhr, status, error) {
            console.error("Update failed:", xhr.status, error);
            alert("Failed to update the purchase order. Check backend connection.");
        }
    });
}

function confirmDelete(id, poNum) {
    $("#deletePoId").val(id);
    $("#deletePoNumSpan").text(poNum);

    let deleteModal = new bootstrap.Modal(document.getElementById('deleteModal'));
    deleteModal.show();
}

function submitDelete() {
    const id = $("#deletePoId").val();

    $.ajax({
        url: `/api/po/purchaseorder/${id}`,
        type: 'DELETE',
        headers: {
            'Authorization': 'Bearer ' + localStorage.getItem("jwtToken")
        },
        success: function (result) {
            let deleteModalEl = document.getElementById('deleteModal');
            let modalInstance = bootstrap.Modal.getInstance(deleteModalEl);
            if(modalInstance) modalInstance.hide();

            refreshTable();
            alert("Purchase Order deleted successfully.");
        },
        error: function (xhr, status, error) {
            console.error("Delete failed:", xhr.status, error);
            alert("Failed to delete purchase order.");
        }
    });
}